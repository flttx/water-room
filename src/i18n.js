export function normalizeLocale(value) { return LOCALES.includes(value) ? value : DEFAULT_LOCALE; }

export function translate(locale, key, vars = {}) {
  const template = messages[normalizeLocale(locale)][key] ?? messages[DEFAULT_LOCALE][key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? `{${name}}`));
}

export function applyTranslations(locale) {
  const lang = normalizeLocale(locale);
  document.documentElement.lang = lang;
  document.title = lang === 'en' ? 'Drowned Halls' : '深水房 · Drowned Halls';
  for (const el of document.querySelectorAll('[data-i18n]')) {
    const parts = translate(lang, el.dataset.i18n).split('<br>');
    el.replaceChildren();
    parts.forEach((part, index) => {
      if (index) el.append(document.createElement('br'));
      el.append(document.createTextNode(part));
    });
  }
  for (const el of document.querySelectorAll('[data-i18n-aria]')) {
    el.setAttribute('aria-label', translate(lang, el.dataset.i18nAria));
  }
  for (const el of document.querySelectorAll('[data-i18n-title]')) {
    el.setAttribute('title', translate(lang, el.dataset.i18nTitle));
  }
}
